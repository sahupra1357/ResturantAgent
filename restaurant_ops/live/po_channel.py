"""Supplier channel: every sent PO becomes a PDF and an e-mail to the supplier.

With SMTP_HOST set the e-mail is sent (STARTTLS + login when configured); otherwise the .eml and .pdf are written to
OUTBOX_DIR for someone to forward. Either way the PO's state is tracked in `po_outbox` (queued / sent / failed), and
a failed send stays in the outbox to retry. The PDF is generated by a tiny built-in writer (Helvetica, one page per
~45 lines), so there is no extra dependency.
"""
from __future__ import annotations

import smtplib
import sqlite3
from email.message import EmailMessage
from pathlib import Path

from restaurant_ops.config import settings
from restaurant_ops.live.events import wall_now


def _esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)").encode("latin-1", "replace").decode("latin-1")


def text_pdf(lines: list[str], title: str = "Purchase order") -> bytes:
    """Minimal valid PDF: text lines, 45 per A4 page, Helvetica 10 pt (title in 14 pt bold)."""
    pages = [lines[i:i + 45] for i in range(0, max(len(lines), 1), 45)] or [[]]
    objs: list[bytes] = []
    objs.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    kids = " ".join(f"{3 + 2 * i} 0 R" for i in range(len(pages)))
    objs.append(f"<< /Type /Pages /Kids [{kids}] /Count {len(pages)} >>".encode())
    font_id = 3 + 2 * len(pages)
    bold_id = font_id + 1
    for i, page in enumerate(pages):
        ops = ["BT", f"/F2 14 Tf 50 800 Td ({_esc(title)}) Tj", "/F1 10 Tf 0 -26 Td 14 TL"]
        for ln in page:
            ops.append(f"({_esc(ln)}) Tj T*")
        ops.append("ET")
        stream = "\n".join(ops).encode("latin-1", "replace")
        objs.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents {4 + 2 * i} 0 R "
                    f"/Resources << /Font << /F1 {font_id} 0 R /F2 {bold_id} 0 R >> >> >>".encode())
        objs.append(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream")
    objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>")
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for n, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{n} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def po_lines(conn: sqlite3.Connection, po_id: str, profile: dict) -> tuple[dict, list[str]]:
    po = dict(conn.execute("SELECT * FROM purchase_orders WHERE po_id=?", (po_id,)).fetchone())
    sup = dict(conn.execute("SELECT * FROM suppliers WHERE id=?", (po["supplier_id"],)).fetchone())
    rows = conn.execute("SELECT l.ingredient_id, i.name, i.unit, l.qty, l.unit_price FROM po_lines l JOIN ingredients i ON i.id=l.ingredient_id "
                        "WHERE l.po_id=? ORDER BY i.name", (po_id,)).fetchall()
    lines = [f"From: {profile.get('name', '')}  {profile.get('address', '')}  {profile.get('phone', '')}",
             f"To:   {sup['name']} <{sup.get('email') or 'no e-mail on file'}>",
             f"PO:   {po_id}    created {po['created_date']}    deliver by {po['expected_delivery']}", "",
             f"{'Item':<34}{'Qty':>10} {'Unit':<4}{'Price':>10}{'Line':>12}", "-" * 72]
    for r in rows:
        lines.append(f"{r['name'][:33]:<34}{r['qty']:>10.2f} {r['unit']:<4}{r['unit_price']:>10.2f}{r['qty'] * r['unit_price']:>12.2f}")
    lines += ["-" * 72, f"{'Total':<60}{po['total']:>12.2f}", "",
              "Please confirm quantities and delivery time by reply. Short-shipping must be notified before dispatch."]
    return {**po, "supplier": sup}, lines


def send_po(conn: sqlite3.Connection, po_id: str, profile: dict, smtp_factory=smtplib.SMTP) -> dict:
    """Render the PO and deliver it (SMTP or outbox). Returns the po_outbox row."""
    po, lines = po_lines(conn, po_id, profile)
    pdf = text_pdf(lines, title=f"Purchase order {po_id}")
    out = Path(settings.OUTBOX_DIR)
    out.mkdir(parents=True, exist_ok=True)
    pdf_path = out / f"{po_id}.pdf"
    pdf_path.write_bytes(pdf)
    to = po["supplier"].get("email") or ""
    msg = EmailMessage()
    msg["From"] = settings.SMTP_FROM
    msg["To"] = to or "orders@unknown-supplier.invalid"
    msg["Subject"] = f"Purchase order {po_id} from {profile.get('name', 'the restaurant')} - deliver {po['expected_delivery']}"
    msg.set_content("\n".join(lines))
    msg.add_attachment(pdf, maintype="application", subtype="pdf", filename=f"{po_id}.pdf")
    eml_path = out / f"{po_id}.eml"
    eml_path.write_bytes(bytes(msg))
    status, err, sent = "queued", None, None
    if settings.SMTP_HOST and to:
        try:
            with smtp_factory(settings.SMTP_HOST, settings.SMTP_PORT, timeout=15) as s:
                if settings.SMTP_STARTTLS:
                    s.starttls()
                if settings.SMTP_USER:
                    s.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
                s.send_message(msg)
            status, sent = "sent", wall_now()
        except Exception as e:  # noqa: BLE001  stays in the outbox for a retry
            status, err = "failed", f"{type(e).__name__}: {e}"
    elif not to:
        err = "supplier has no e-mail on file: forward the PDF from the outbox"
    conn.execute("INSERT OR REPLACE INTO po_outbox (po_id, supplier_id, email, pdf_path, eml_path, status, sent_ts, error) VALUES (?,?,?,?,?,?,?,?)",
                 (po_id, po["supplier_id"], to, str(pdf_path), str(eml_path), status, sent, err))
    conn.commit()
    return dict(conn.execute("SELECT * FROM po_outbox WHERE po_id=?", (po_id,)).fetchone())


def outbox(conn: sqlite3.Connection) -> list[dict]:
    return [dict(r) for r in conn.execute(
        "SELECT o.*, p.total, p.expected_delivery, p.created_date FROM po_outbox o JOIN purchase_orders p ON p.po_id=o.po_id ORDER BY o.po_id DESC")]
